/**
 * Get locations by state (for filtering)
 */
export const getLocationsByState = (state: string): SelectOption[] => {
    const stateStr = String(state).toLowerCase();
    switch (stateStr) {
        case 'lagos':
            return lagosLocations;
        case 'abuja':
        case 'fct':
            return abujaLocations;
        case 'rivers':
            return riversLocations;
        case 'oyo':
            return oyoLocations;
        default:
            return allNigeriaLocations;
    }
};

/**
 * Search locations by query
 */
export const searchLocations = (query: string): SelectOption[] => {
    if (!query || query.trim().length === 0) {
        return popularLocations;
    }

    const searchTerm = query.toLowerCase();
    return allNigeriaLocations.filter(location =>
        location.label.toLowerCase().includes(searchTerm) ||
        String(location.value).toLowerCase().includes(searchTerm)
    );
};
